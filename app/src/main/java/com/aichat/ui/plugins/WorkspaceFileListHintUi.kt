package com.aichat.ui.plugins

/**
 * 工作区文件列表一次最多**显示**多少个。
 *
 * ⚠️ 这个数和工作区的 [com.aichat.plugin.workspace.PluginWorkspace.MAX_ENTRIES]（256）
 * 是**两个不同的上限**，别混：
 *
 * | 上限 | 值 | 管的是 |
 * |---|---|---|
 * | `MAX_ENTRIES` | 256 | **工作区能存**多少（超了插件写不进去） |
 * | `MAX_VISIBLE_FILES` | 30 | **这一屏能列**多少（超了照样存着，只是不显示） |
 *
 * 原来那句话写的是「还有 N 个文件没有列出来（**工作区最多 256 个**）」——
 * 256 字面为真，但读者会推出「**是 256 这个上限导致只显示 30 个**」，
 * 而真正的原因是这里的 30。**两个上限混进一句话，两个数都对，结论是错的**（§111）。
 * 而且工作区用量（`N 个文件 · X KB / 8.0 MB`）本来就单独显示在列表上方，
 * 在这句里再提一次纯属噪音。
 *
 * ⚠️ 这个函数**单独一个文件**：可见性守卫要读 `PluginDetailScreen.kt` 的源码文本断言
 * 含 `workspaceMoreFilesHint(`，函数和调用点同处一个文件的话，那句断言会被**函数自己的
 * 定义那一行**匹配到 ⇒ 调用删掉了守卫照样绿（§111.7）。
 */
internal const val MAX_VISIBLE_FILES = 30

/**
 * 文件列表**顶到了显示上限**时那句提示。三件事缺一不可（§111.2）：
 *
 * 1. **上限是多少** —— 从 [MAX_VISIBLE_FILES] 插值，不手写
 * 2. **被藏起来的是哪些** —— 「按名称排序列了前 30 个」。不说的话用户没法预测
 *    哪几个在、哪几个不在，只能一个个对着数
 * 3. **最要紧的那半句：它们没有删掉** —— 列表到此为止最容易被读成「工作区里就这些」，
 *    而工作区里的东西是插件攒下来的，用户会以为丢了
 *
 * 末尾给一个**这一页就能做的动作**（每行都有「删除」）。只说限制不给动作，
 * 等于把问题丢回给用户。
 *
 * ⚠️ 文案里不能带 markdown 记号：Compose 的 `Text` 不认 markdown，
 * `**没有删掉**` 会把星号**原样显示**给用户（§111.11）。
 */
internal fun workspaceMoreFilesHint(hidden: Int): String =
    "还有 $hidden 个文件没有列出来 —— 这里按名称排序列了前 $MAX_VISIBLE_FILES 个。" +
        "它们没有删掉，删掉列出来的某几个，后面的就会顶上来。"
