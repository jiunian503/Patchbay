package com.aichat.ui.conversations

/**
 * 搜索结果区顶部那一行。
 *
 * ## 为什么不能只写「找到 N 条」
 *
 * 检索**是有上限的**（一次最多 `ConversationSearch.DEFAULT_LIMIT` 条），而这个上限
 * 原来一个字都没露在外面：匹配 200 条时那一行写的是「找到 50 条」—— 那是**事实错误**。
 * 用户读到的结论是「库里只有 50 条匹配」，于是他不再往下找，也永远不会知道
 * 剩下那些是因为上限没列出来。判据见 §111：**没说的上限会把人引到错结论上。**
 *
 * ## 为什么给「把词写具体」这条出路
 *
 * 检索没有翻页（再搜一次还是前 50 条），所以用户唯一能做的事就是**换一个更窄的词**。
 * 只说「只列了一部分」等于把问题丢回给他。
 *
 * ## ⚠️ 为什么它单独一个文件，而不是待在 `ConversationSearchScreen.kt` 里
 *
 * 因为守它的那条测试要**读页面源码文本**、断言里面出现了这次调用
 * （`SearchResultHeaderTest` 里的 `搜索结果页真的把它显示出来了`）。
 * 函数和调用点同处一个文件的话，`contains("searchResultHeader(")`
 * **会被函数自己的定义那一行匹配到** —— 那样即使调用被删掉，守卫照样绿。
 *
 * 这不是假设：第一版就是这么写的，变异检验（把调用换回写死的「找到 N 条」）
 * **一条都没红**。**守卫自己骗自己**比没有守卫更糟 —— 它是绿的。
 */
internal fun searchResultHeader(shown: Int, truncated: Boolean): String =
    if (truncated) {
        "匹配的消息很多，这里只列了前 $shown 条 —— 把关键词写具体一点，结果会少一些。"
    } else {
        "找到 $shown 条"
    }
