package com.aichat.ui.conversations

/**
 * 侧边栏列表底部那句「更早的没列出来」。
 *
 * ## 为什么非说不可
 *
 * 侧边栏一次最多列 `ConversationStore.DEFAULT_CONVERSATION_LIMIT` 个会话，
 * 而且**没有分页**（再拉开一次还是同一批）。不说的话，第 101 个往后的会话
 * **静默消失** —— 用户看到的不是「列表有上限」，而是「我的会话没了」。
 * 这是这一整轮里最像丢数据的一处，所以这句话里最要紧的四个字是
 * **「没有删掉」**。
 *
 * ⚠️ 文案里**不能带 markdown 记号**：`Text` 是原样渲染的，
 * `**没有删掉**` 会把星号一起显示出来。所以这里只用「」引号强调。
 *
 * ## 为什么给出路
 *
 * 侧边栏没有「加载更多」，所以用户自己没法把剩下的翻出来。
 * 但「搜索历史」搜的是**全部消息**（FTS 索引，不受这个上限约束），
 * 所以按内容找得到更早的会话 —— 这是唯一一条真实的路，得写出来。
 *
 * ## ⚠️ 为什么它单独一个文件
 *
 * 因为守它的测试要**读 `ConversationDrawer.kt` 的源码文本**、断言里面出现了
 * 这次调用。函数和调用点同处一个文件的话，`contains("drawerMoreHint(")`
 * **会被函数自己的定义那一行匹配到** —— 那样调用删掉了守卫照样是绿的
 * （`searchResultHeader` 就踩过这一脚，见 §111.7）。
 */
internal fun drawerMoreHint(shown: Int): String =
    "侧边栏最多列 $shown 个会话 —— 更早的那些没有删掉，只是没显示在这里。" +
        "用下面的「搜索历史」能按内容找到它们。"
