 * App 自己的图标集。
 *
 * ## 为什么不引 `material-icons-core`
 *
 * Material3 1.4.0 **已经不再把它带进来**了 —— `gradle :app:dependencies` 里
 * 搜 `icons` 一条都没有。而这个包本身已经被官方标记为弃用。
 * 为了十来个图标去加一个弃用的依赖，还得自己钉版本号防冲突，不划算。
 *
 * ## 自己写反而更好
 *
 * 这十几条就是 24×24 视口的路径数据，是**规范的一部分**，不会变。
